#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Import Catppuccin file icons and their associations from a vscode-icons checkout.

Usage: scripts/catppuccin_icons.py <path-to-catppuccin/vscode-icons-checkout>

Copies the `icons/css-variables/*.svg` files Strata uses into `data/icons/catppuccin/`,
rewrites `src/ui/browser/entry/catppuccin.rs` from `src/defaults/fileIcons.ts`, and
refreshes the `icons/catppuccin/` entries in `data/strata.gresource.xml`.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ICON_DIR = REPO / "data/icons/catppuccin"
MODULE = REPO / "src/ui/browser/entry/catppuccin.rs"
GRESOURCE = REPO / "data/strata.gresource.xml"
PREFIX = "strata-ctp-"

# Non-code categories keep Strata's Lucide icons, and a few upstream files render
# badly or carry colors outside the palette.
EXCLUDED = {
    "3d", "adobe-ae", "adobe-ai", "adobe-id", "adobe-ps", "adobe-xd", "audio", "video",
    "image", "svg", "font", "pdf", "zip", "exe", "binary", "ms-excel", "ms-powerpoint",
    "ms-word", "text", "csv", "log", "org", "todo", "_file", "_folder", "_folder_open",
    "_root", "_root_open", "symlink", "figma", "sketch", "drawio", "midi", "url", "key",
    "certificate", "favicon", "search", "hacking", "rdata", "phtml", "wally", "lock",
}
# Icons without upstream associations that Strata's own extension table routes to.
EXTRA = ["config"]


def parse_file_icons(upstream: Path) -> dict[str, dict[str, list[str]]]:
    source = (upstream / "src/defaults/fileIcons.ts").read_text()
    source = re.sub(r"//[^\n]*", "", source)
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    body = source[source.index("const fileIcons: FileIcons = {") :]
    icons: dict[str, dict[str, list[str]]] = {}
    for match in re.finditer(r"\n  '([^']+)': \{(.*?)\n  \}", body, flags=re.S):
        name, block = match.group(1), match.group(2)
        entry: dict[str, list[str]] = {}
        for key in ("fileExtensions", "fileNames"):
            key_match = re.search(key + r":\s*\[(.*?)\]", block, flags=re.S)
            if key_match:
                entry[key] = re.findall(r"'([^']*)'", key_match.group(1))
        icons[name] = entry
    return icons


def constant(icon: str) -> str:
    return icon.upper().replace("-", "_")


def render_module(used: list[str], names: dict[str, str], extensions: dict[str, str]) -> str:
    lines = [
        "// SPDX-License-Identifier: MIT",
        "//! Catppuccin file icons and their upstream filename and extension associations.",
        "//! Generated by `scripts/catppuccin_icons.py` from catppuccin/vscode-icons",
        "//! `src/defaults/fileIcons.ts`; do not edit by hand.",
        "",
    ]
    lines += [f'pub const {constant(icon)}: &str = "{PREFIX}{icon}";' for icon in used]
    lines += ["", "static NAMES: &[(&str, &str)] = &["]
    lines += [f'    ("{key}", {constant(names[key])}),' for key in sorted(names)]
    lines += ["];", "", "static EXTENSIONS: &[(&str, &str)] = &["]
    lines += [f'    ("{key}", {constant(extensions[key])}),' for key in sorted(extensions)]
    lines += [
        "];",
        "",
        "pub(super) fn icon_for_lowercased_name(lowered: &str) -> Option<&'static str> {",
        "    NAMES",
        "        .binary_search_by_key(&lowered, |(name, _)| name)",
        "        .ok()",
        "        .map(|index| NAMES[index].1)",
        "}",
        "",
        "/// Matches the longest dotted suffix first so `d.ts` wins over `ts`.",
        "pub(super) fn icon_for_lowercased_extension(lowered: &str) -> Option<&'static str> {",
        "    lowered",
        "        .match_indices('.')",
        "        .map(|(index, _)| &lowered[index + 1..])",
        "        .filter(|suffix| !suffix.is_empty())",
        "        .find_map(|suffix| {",
        "            EXTENSIONS",
        "                .binary_search_by_key(&suffix, |(extension, _)| extension)",
        "                .ok()",
        "                .map(|index| EXTENSIONS[index].1)",
        "        })",
        "}",
        "",
    ]
    return "\n".join(lines)


def update_gresource(used: list[str]) -> None:
    text = GRESOURCE.read_text()
    text = re.sub(r"    <file>icons/catppuccin/[^<]+</file>\n", "", text)
    entries = "".join(f"    <file>icons/catppuccin/{PREFIX}{icon}.svg</file>\n" for icon in used)
    marker = "  </gresource>\n"
    assert text.count(marker) == 1
    GRESOURCE.write_text(text.replace(marker, entries + marker))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    upstream = Path(sys.argv[1])
    icons = parse_file_icons(upstream)
    names: dict[str, str] = {}
    extensions: dict[str, str] = {}
    for icon, entry in icons.items():
        if icon in EXCLUDED or icon.startswith("folder"):
            continue
        for value in entry.get("fileNames", []):
            names[value.lower()] = icon
        for value in entry.get("fileExtensions", []):
            extensions[value.lower()] = icon
    used = sorted(set(names.values()) | set(extensions.values()) | set(EXTRA))

    if ICON_DIR.exists():
        shutil.rmtree(ICON_DIR)
    ICON_DIR.mkdir(parents=True)
    for icon in used:
        shutil.copyfile(
            upstream / "icons/css-variables" / f"{icon}.svg", ICON_DIR / f"{PREFIX}{icon}.svg"
        )
    MODULE.write_text(render_module(used, names, extensions))
    update_gresource(used)
    print(json.dumps({"icons": len(used), "names": len(names), "extensions": len(extensions)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
