fn solid(width: u32, height: u32, color: [u8; 3]) -> Vec<u8> {
    let mut image = Pixmap::new(width, height).expect("pixmap");
    image.fill(Color::from_rgba8(color[0], color[1], color[2], 255));
    image.encode_png().expect("png")
}

fn base64(bytes: &[u8]) -> String {
    const TABLE: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut encoded = String::new();
    let (chunks, rest) = bytes.as_chunks::<3>();
    for chunk in chunks {
        let value = (u32::from(chunk[0]) << 16) | (u32::from(chunk[1]) << 8) | u32::from(chunk[2]);
        for shift in [18, 12, 6, 0] {
            encoded.push(TABLE[((value >> shift) & 63) as usize] as char);
        }
    }
    if rest.len() == 1 {
        let value = u32::from(rest[0]) << 16;
        encoded.push(TABLE[((value >> 18) & 63) as usize] as char);
        encoded.push(TABLE[((value >> 12) & 63) as usize] as char);
        encoded.push('=');
        encoded.push('=');
    } else if rest.len() == 2 {
        let value = (u32::from(rest[0]) << 16) | (u32::from(rest[1]) << 8);
        encoded.push(TABLE[((value >> 18) & 63) as usize] as char);
        encoded.push(TABLE[((value >> 12) & 63) as usize] as char);
        encoded.push(TABLE[((value >> 6) & 63) as usize] as char);
        encoded.push('=');
    }
    encoded
}

fn block(kind: &str, width: u32, height: u32, bytes: &[u8]) -> String {
    let encoded = base64(bytes);
    let mut text = format!("; {kind} begin {width}x{height} {}\n", encoded.len());
    for chunk in encoded.as_bytes().chunks(76) {
        text.push_str("; ");
        text.push_str(std::str::from_utf8(chunk).expect("base64"));
        text.push('\n');
    }
    text.push_str(&format!("; {kind} end\n"));
    text
}

fn rendered(name: &str, bytes: &[u8]) -> Result<Vec<u8>, String> {
    let directory = tempfile::tempdir().expect("fixture directory");
    let path = directory.path().join(name);
    fs::write(&path, bytes).expect("fixture");
    thumbnail(&path, 64, 64, &|_| {})
}

fn red_channel(png: &[u8]) -> u8 {
    Pixmap::decode_png(png)
        .expect("png")
        .pixel(0, 0)
        .expect("pixel")
        .red()
}

#[test]
fn names_gcode_and_keeps_the_largest_embedded_image() {
    for name in ["plate.gcode", "plate.GCO", "plate.bgcode"] {
        assert_eq!(
            ModelFormat::for_name(OsStr::new(name)),
            Some(ModelFormat::Gcode),
            "{name}"
        );
    }
    assert_eq!(ModelFormat::for_name(OsStr::new("toolpath.nc")), None);

    let red = solid(1, 1, [255, 0, 0]);
    let green = solid(4, 4, [0, 255, 0]);
    let mut file = String::from("; generated by test\n");
    file.push_str(&block("thumbnail", 1, 1, &red));
    file.push_str(&block("thumbnail_PNG", 4, 4, &green));
    file.push_str("G1 X1 Y2\n");
    file.push_str(&block("thumbnail", 8, 8, &red));
    let png = rendered("plate.gcode", file.as_bytes()).expect("thumbnail");
    assert_eq!(red_channel(&png), 0);
    let (width, height) = crate::sandbox::png_dimensions(&png).expect("dimensions");
    assert_eq!((width, height), (4, 4));
}

#[test]
fn corrupt_larger_image_falls_through_and_crlf_comments_still_decode() {
    let red = solid(2, 2, [255, 0, 0]);
    let file = format!(
        "{}\r\nG1 X0\r\n",
        block("thumbnail", 2, 2, &red).replace('\n', "\r\n")
    );
    let mut both = block("thumbnail", 80, 80, b"this is not an image");
    both.push_str(&file.replace("\r\n", "\n"));
    let png = rendered("plate.gcode", both.as_bytes()).expect("smaller image");
    assert_eq!(red_channel(&png), 255);

    let hidden = format!("G1 X0\n{}", block("thumbnail", 2, 2, &red));
    let error = rendered("late.gcode", hidden.as_bytes()).expect_err("command ends the header");
    assert_eq!(error, NO_GCODE_THUMBNAIL);
}

#[test]
fn jpeg_and_qoi_comments_decode_and_a_missing_thumbnail_stays_specific() {
    let image =
        image::DynamicImage::ImageRgb8(image::RgbImage::from_pixel(8, 6, image::Rgb([20, 40, 60])));
    let mut jpeg = std::io::Cursor::new(Vec::new());
    image
        .write_to(&mut jpeg, image::ImageFormat::Jpeg)
        .expect("jpeg");
    let jpeg = jpeg.into_inner();
    let png = rendered("jpeg.gcode", block("thumbnail_JPG", 8, 6, &jpeg).as_bytes())
        .expect("jpeg thumbnail");
    let (width, height) = crate::sandbox::png_dimensions(&png).expect("jpeg png");
    assert_eq!((width, height), (8, 6));

    // 1×1 QOI: header, one QOI_OP_RGBA red pixel, end marker.
    let qoi = [
        b'q', b'o', b'i', b'f', 0, 0, 0, 1, 0, 0, 0, 1, 4, 0, 0xFF, 255, 0, 0, 255, 0, 0, 0, 0, 0,
        0, 0, 1,
    ];
    let png = rendered("qoi.gco", block("thumbnail_QOI", 1, 1, &qoi).as_bytes()).expect("qoi");
    assert_eq!(red_channel(&png), 255);

    let directory = tempfile::tempdir().expect("fixture directory");
    let path = directory.path().join("plain.gcode");
    fs::write(&path, b"; no thumbnail here\nG1 X0\n").expect("plain gcode");
    let error = match super::super::render_reporting(
        &path,
        "gcode:64x64:cccccc:101010:front-left",
        &|_| {},
    ) {
        Err(error) => error,
        Ok(_) => panic!("expected a missing thumbnail"),
    };
    assert_eq!(error, NO_GCODE_THUMBNAIL);
}

#[test]
fn header_scan_stops_at_its_cap_but_finishes_a_block_already_started() {
    let red = solid(2, 2, [255, 0, 0]);
    let thumb = block("thumbnail", 2, 2, &red);
    let pad = "; pad\n";
    let late = format!(
        "{}{thumb}",
        pad.repeat((MAX_GCODE_HEADER_BYTES as usize / pad.len()) + 3)
    );
    assert_eq!(
        rendered("late.gcode", late.as_bytes()).expect_err("past the header"),
        NO_GCODE_THUMBNAIL
    );

    let mut early = String::new();
    while early.len() + thumb.len() <= MAX_GCODE_HEADER_BYTES as usize {
        early.push_str(pad);
    }
    early.push_str(&thumb);
    assert!(early.len() as u64 > MAX_GCODE_HEADER_BYTES);
    let png = rendered("edge.gcode", early.as_bytes()).expect("block crosses the cap");
    assert_eq!(red_channel(&png), 255);
}

#[test]
fn binary_gcode_reads_the_thumbnail_without_the_toolpath() {
    let red = solid(1, 1, [255, 0, 0]);
    let green = solid(3, 3, [0, 180, 0]);
    let bytes = bgcode(&[(&red, 1, 1), (&green, 3, 3)]);
    let png = rendered("plate.bgcode", &bytes).expect("binary thumbnail");
    assert_eq!(red_channel(&png), 0);
    let (width, height) = crate::sandbox::png_dimensions(&png).expect("dimensions");
    assert_eq!((width, height), (3, 3));
}

fn bgcode(images: &[(&[u8], u16, u16)]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend(b"GCDE");
    out.extend(1u32.to_le_bytes());
    out.extend(1u16.to_le_bytes());
    // Compressed printer metadata. Its uncompressed size is a lie so a parser
    // that skips the wrong field walks into the thumbnail.
    out.extend(3u16.to_le_bytes());
    out.extend(1u16.to_le_bytes());
    out.extend(1_000u32.to_le_bytes());
    out.extend(4u32.to_le_bytes());
    out.extend(0u16.to_le_bytes());
    out.extend(b"junk");
    out.extend(0u32.to_le_bytes());
    for (png, width, height) in images {
        out.extend(5u16.to_le_bytes());
        out.extend(0u16.to_le_bytes());
        out.extend(u32::try_from(png.len()).expect("png length").to_le_bytes());
        out.extend(0u16.to_le_bytes());
        out.extend(width.to_le_bytes());
        out.extend(height.to_le_bytes());
        out.extend(*png);
        out.extend(0u32.to_le_bytes());
    }
    out.extend(1u16.to_le_bytes());
    out.extend(0u16.to_le_bytes());
    out.extend(u32::MAX.to_le_bytes());
    out
}
