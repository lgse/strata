#!/usr/bin/env python3
"""Writes emoji.tsv, the IconPicker's bundled emoji (C20d), from Unicode's data.

Sources (both under the Unicode License V3, LICENSE-Unicode.txt beside this file):

- Unicode emoji 18.0, https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt
  (dated 2026-04-30): the emoji, their groups, the version each arrived in and their names.
- CLDR release-49, https://github.com/unicode-org/cldr/tree/release-49, files
  common/annotations/en.xml and common/annotationsDerived/en.xml: the keywords.

Run by hand when the sources move, with the three files downloaded beside each other:

    python3 -I generate.py emoji-test.txt annotations-en.xml annotationsDerived-en.xml > emoji.tsv

Kept: fully-qualified emoji, in the file's order. Left out: the Component group (skin tone and
hair swatches) and every emoji with a skin tone modifier (the picker offers no skin tones,
deviation D2). Every version is kept; the picker caps them at run time (15.1 by default).

Format, one emoji a line after its group's `@` line, tab-separated:
glyph, the version it arrived in, its name, and its keywords joined by `|` (the name itself
left out). Lines starting with `# ` are comments (the keycap #️⃣ starts with `#`).
"""

import re
import sys
import xml.etree.ElementTree as ET

TONE = re.compile("[\U0001F3FB-\U0001F3FF]")
LINE = re.compile(r"([0-9A-F ]+);\s*fully-qualified\s*#\s*(\S+)\s+E([\d.]+)\s+(.*)")


def keywords(paths):
    out = {}
    for path in paths:
        for a in ET.parse(path).getroot().iter("annotation"):
            if a.get("type") == "tts" or not a.text:
                continue
            out.setdefault(a.get("cp"), [k.strip() for k in a.text.split("|")])
    return out


def main(test, *annotations):
    kw = keywords(annotations)
    print("# Generated by generate.py from Unicode emoji 18.0 emoji-test.txt and CLDR release-49")
    print("# en annotations (Unicode License V3, LICENSE-Unicode.txt). Do not edit by hand.")
    group = None
    for line in open(test, encoding="utf-8"):
        m = re.match(r"# group: (.*)", line)
        if m:
            group = m.group(1).strip()
            if group != "Component":
                print(f"@{group}")
            continue
        m = LINE.match(line)
        if not m or group == "Component":
            continue
        glyph, version, name = m.group(2), m.group(3), m.group(4).strip()
        if TONE.search(glyph):
            continue
        words = kw.get(glyph) or kw.get(glyph.replace("\ufe0f", "")) or []
        words = [w for w in words if w and w != name and "\t" not in w and "|" not in w]
        print(f"{glyph}\t{version}\t{name}\t{'|'.join(words)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
